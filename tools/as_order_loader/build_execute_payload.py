#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Сборка execute_code payload из JSON-спецификации для прямой загрузки в 1С.

Usage:
    .venv/bin/python tools/as_order_loader/build_execute_payload.py positions.json > payload.json
    curl -s -m 280 -X POST http://127.0.0.1:6005/api/execute_code \
         -H 'Content-Type: application/json' -d @payload.json

positions.json — массив позиций (формат см. в шапке as_order_loader.bsl).
Обязательные ключи: article, qty, thickness, material, params, comment;
shina, conn0, conn1 — всегда присутствуют (json_positions.py гарантирует).

Inline-BSL — развёрнутая копия логики as_order_loader.bsl (объявления
процедур/функций через Выполнить невозможны, поэтому код «распластан»).
При изменении as_order_loader.bsl обновляйте и этот шаблон; контроль
согласованности — tests/test_json_positions.py и end-to-end прогон.
"""
import base64
import json
import sys

# Тройные одинарные кавычки: внутри BSL встречаются """ (экранированные
# кавычки 1С), которые рвут строку в двойных кавычках.
BSL_TEMPLATE = '''
Данные64 = "{b64}";
ДанныеСтрока = ПолучитьСтрокуИзДвоичныхДанных(ПолучитьДвоичныеДанныеИзBase64Строки(Данные64));
Чтение = Новый ЧтениеJSON;
Чтение.УстановитьСтроку(ДанныеСтрока);
Позиции = ПрочитатьJSON(Чтение); // структуры — обращение по точке

Ошибки = Новый Массив;
Предупреждения = Новый Массив;

НачатьТранзакцию();
Попытка
	ДокОбъект = Документы.асСпецификацияЗаказа.СоздатьДокумент();
	ДокОбъект.Дата = ТекущаяДатаСеанса();
	ДокОбъект.Комментарий = "{order_comment}";

	НомерСтроки = 0;
	Для Каждого П Из Позиции Цикл
		НомерСтроки = НомерСтроки + 1;
		Стр = ДокОбъект.Товары.Добавить();

		Продукт = Справочники.асПродукция.НайтиПоРеквизиту("Артикул", П.article);
		Если Не ЗначениеЗаполнено(Продукт) Тогда
			Ошибки.Добавить("Строка " + НомерСтроки + ": не найден продукт """ + П.article + """");
		Иначе
			Стр.Продукт = Продукт;
			Стр.Номенклатура = Продукт.Продукт;
			Стр.АртикулПродукции = П.article;
			ПозДефиса = СтрНайти(П.article, "-");
			Стр.АртикулГруппы = ?(ПозДефиса > 0, Лев(П.article, ПозДефиса - 1), П.article);
			Стр.ГруппаПродукцииСтр = Продукт.ГруппаПродукции;
			Стр.СечениеСтр = Продукт.ВидСечения;
		КонецЕсли;

		Стр.n = П.qty;
		Стр.np = П.qty;
		Стр.t = П.thickness;
		Стр.t2 = П.thickness;

		Стр.Материал = Справочники.асМатериалы.НайтиПоНаименованию(П.material, Истина);
		Стр.Материал2 = Стр.Материал;
		Если Не ЗначениеЗаполнено(Стр.Материал) Тогда
			Ошибки.Добавить("Строка " + НомерСтроки + ": не найден материал """ + П.material + """");
		КонецЕсли;

		Стр.КомментарийКПродукцииИзOnLine = П.comment;

		// Шина на соединение (правила техотдела; нерж 65 -> нерж-вариант).
		Если ЗначениеЗаполнено(П.shina) Тогда
			Нерж = СтрНайти(П.material, "нерж") > 0;
			Если Нерж И П.shina = "65" Тогда
				ИмяШины = "Шина 20(нерж.430) / УГФ 65(нерж.430)";
			Иначе
				ИмяШины = ?(П.shina = "105", "Шина 30 / УГФ 105", "Шина 20 / УГФ " + П.shina);
			КонецЕсли;
			Стр.МатериалНаСоединение0 = Справочники.асПродукция.НайтиПоНаименованию(ИмяШины, Истина);
			Стр.МатериалНаСоединение1 = Стр.МатериалНаСоединение0;
			Если Не ЗначениеЗаполнено(Стр.МатериалНаСоединение0) Тогда
				Ошибки.Добавить("Строка " + НомерСтроки + ": не найдена шина """ + ИмяШины + """");
			КонецЕсли;
		КонецЕсли;

		// Соединения: 6 = "Шина / уголок", 2 = "Без соединения".
		Если П.conn0 = "6" Или П.conn0 = "2" Тогда
			ИмяСоед = ?(П.conn0 = "6", "Шина / уголок", "Без соединения");
			Стр.СоединениеВоздуховода_c0 = Справочники.асСоединениеВоздуховодов.НайтиПоНаименованию(ИмяСоед, Истина);
		КонецЕсли;
		Если П.conn1 = "6" Или П.conn1 = "2" Тогда
			ИмяСоед = ?(П.conn1 = "6", "Шина / уголок", "Без соединения");
			Стр.СоединениеВоздуховода_c1 = Справочники.асСоединениеВоздуховодов.НайтиПоНаименованию(ИмяСоед, Истина);
		КонецЕсли;

		Для Каждого КЗ Из П.params Цикл
			Попытка
				Стр[КЗ.Ключ] = КЗ.Значение;
			Исключение
				Предупреждения.Добавить("Строка " + НомерСтроки + ": параметр """ + КЗ.Ключ + """ не применён");
			КонецПопытки;
		КонецЦикла;

		// Характеристика: найти существующую или создать (обход бага поиска
		// в «Оформить заказ» — без заполненной характеристики оформление падает
		// «Рабочее наименование не уникально», см. docs/BACKLOG.md).
		Если ЗначениеЗаполнено(Стр.Номенклатура) Тогда
			МатХ = Строка(Стр.Материал2.НаименованиеДляПечати);
			D_ = Формат(Стр.D0, "ЧГ=");
			A_ = Формат(Стр.A0, "ЧГ=");
			B_ = Формат(Стр.B0, "ЧГ=");
			A1_ = Формат(Стр.A1, "ЧГ=");
			B1_ = Формат(Стр.B1, "ЧГ=");
			L_ = Формат(Стр.L0, "ЧГ=");
			Канд = Новый Массив;
			Если Стр.D0 > 0 Тогда
				Если Стр.L0 > 0 Тогда
					Канд.Добавить("Ф" + D_ + "-" + L_ + "  " + МатХ);
				КонецЕсли;
				Канд.Добавить("Ф" + D_ + "  " + МатХ);
			КонецЕсли;
			Если Стр.A0 > 0 И Стр.B0 > 0 Тогда
				Если Стр.A1 > 0 И Стр.B1 > 0 Тогда
					Если Стр.L0 > 0 Тогда
						Канд.Добавить(A_ + "x" + B_ + "/" + A1_ + "x" + B1_ + "-" + L_ + "  " + МатХ);
					КонецЕсли;
					Канд.Добавить(A_ + "x" + B_ + "/" + A1_ + "x" + B1_ + "  " + МатХ);
				КонецЕсли;
				Если Стр.L0 > 0 Тогда
					Канд.Добавить(A_ + "x" + B_ + "-" + L_ + "  " + МатХ);
				КонецЕсли;
				Канд.Добавить(A_ + "x" + B_ + "  " + МатХ);
			КонецЕсли;
			Хар = Неопределено;
			Для Каждого Кандидат Из Канд Цикл
				НайдХ = Справочники.ХарактеристикиНоменклатуры.НайтиПоНаименованию(Кандидат, Истина, , Стр.Номенклатура);
				Если ЗначениеЗаполнено(НайдХ) Тогда
					Хар = НайдХ;
					Прервать;
				КонецЕсли;
			КонецЦикла;
			Если Хар = Неопределено И Канд.Количество() > 0 Тогда
				СпрХ = Справочники.ХарактеристикиНоменклатуры.СоздатьЭлемент();
				СпрХ.Владелец = Стр.Номенклатура;
				СпрХ.Наименование = Канд[0];
				СпрХ.НаименованиеПолное = Канд[0];
				СпрХ.Записать();
				Хар = СпрХ.Ссылка;
			КонецЕсли;
			Если Хар <> Неопределено Тогда
				Стр.Характеристика = Хар;
			КонецЕсли;
		КонецЕсли;

		// Производные размеры из регистра настроек продукции (иначе S в минус).
		Если ЗначениеЗаполнено(Стр.Продукт) Тогда
			ЗапросН = Новый Запрос("ВЫБРАТЬ Н.ПараметрПродукции, Н.Вариант, Н.КонстантаЗначения, Н.ЗависимыйПараметр, Н.Оператор, Н.ЧислоX ИЗ РегистрСведений.асНастройкиПродукции КАК Н ГДЕ Н.Продукт = &Продукт");
			ЗапросН.УстановитьПараметр("Продукт", Стр.Продукт);
			ВыборкаН = ЗапросН.Выполнить().Выбрать();
			Пока ВыборкаН.Следующий() Цикл
				ИмяП = Строка(ВыборкаН.ПараметрПродукции);
				Попытка
					Если Стр[ИмяП] = 0 Тогда
						Если ВыборкаН.Вариант = "Вариант1" Тогда
							Стр[ИмяП] = ВыборкаН.КонстантаЗначения;
						ИначеЕсли ВыборкаН.Вариант = "Вариант2" Тогда
							База = Стр[Строка(ВыборкаН.ЗависимыйПараметр)];
							Если ВыборкаН.Оператор = Справочники.асАрифметическиеОператоры.Сложение Тогда
								Стр[ИмяП] = База + ВыборкаН.ЧислоX;
							ИначеЕсли ВыборкаН.Оператор = Справочники.асАрифметическиеОператоры.Вычитание Тогда
								Стр[ИмяП] = База - ВыборкаН.ЧислоX;
							ИначеЕсли ВыборкаН.Оператор = Справочники.асАрифметическиеОператоры.Умножение Тогда
								Стр[ИмяП] = База * ВыборкаН.ЧислоX;
							ИначеЕсли ВыборкаН.Оператор = Справочники.асАрифметическиеОператоры.Деление Тогда
								Стр[ИмяП] = ?(ВыборкаН.ЧислоX = 0, 0, База / ВыборкаН.ЧислоX);
							КонецЕсли;
						КонецЕсли;
					КонецЕсли;
				Исключение
				КонецПопытки;
			КонецЦикла;
		КонецЕсли;
	КонецЦикла;

	// Расчёт S/M/цен штатной обработкой (паритет с кнопкой «Расчёт»).
	О = Обработки.асВводНовогоЗаказа.Создать();
	О.ДатаУстановкиЦен = ТекущаяДатаСеанса();
	Попытка О.ТекущаяПрограмма1С = "КА"; Исключение КонецПопытки;
	Попытка О.УчитыватьЗамкиВРасчетеПлощадиДляСчета = Истина; Исключение КонецПопытки;

	КолонкиЗаказы = О.Заказы.Выгрузить().Колонки;
	Для Каждого Стр Из ДокОбъект.Товары Цикл
		З = О.Заказы.Добавить();
		Для Каждого к Из КолонкиЗаказы Цикл
			Попытка З[к.Имя] = Стр[к.Имя]; Исключение КонецПопытки;
		КонецЦикла;
		З.ТребуетсяПересчет = Истина;
	КонецЦикла;

	О.РедактироватьВсеНаКлиенте_ДляИзмененныхВМодуле();

	Инд = 0;
	Для Каждого Стр Из ДокОбъект.Товары Цикл
		Инд = Инд + 1;
		З = О.Заказы[Инд - 1];
		Для Каждого к Из КолонкиЗаказы Цикл
			Попытка Стр[к.Имя] = З[к.Имя]; Исключение КонецПопытки;
		КонецЦикла;
		Если Стр.ЦенаЕд = 0 Тогда
			Предупреждения.Добавить("Строка " + Инд + " (" + Стр.АртикулПродукции + "): цена 0 — проверьте прайс");
		КонецЕсли;
	КонецЦикла;

	ДокОбъект.Записать();

	Части = Новый Массив;
	Для Каждого Стр Из ДокОбъект.Товары Цикл
		Части.Добавить(
			Строка(Стр.НомерСтроки) + "|" + Стр.АртикулПродукции
			+ "|t=" + Строка(Стр.t)
			+ "|мат=" + Строка(Стр.Материал)
			+ "|шина0=" + Строка(Стр.МатериалНаСоединение0)
			+ "|с0=" + Строка(Стр.СоединениеВоздуховода_c0)
			+ "|тип=" + Строка(Стр.ТипЦеныПоПрайсу)
			+ "|цена=" + Строка(Стр.ЦенаЕд)
			+ "|S=" + Строка(Стр.S)
			+ "|n=" + Строка(Стр.n));
	КонецЦикла;

	{mark_delete}ДокОбъект.УстановитьПометкуУдаления(Истина);

	Итог = "ЗАКАЗ " + ДокОбъект.Номер + " | строк=" + ДокОбъект.Товары.Количество()
		+ " | ошибок=" + Ошибки.Количество()
		+ " | предупр=" + Предупреждения.Количество()
		+ ?(Ошибки.Количество() > 0, " | " + СтрСоединить(Ошибки, "; "), "")
		+ ?(Предупреждения.Количество() > 0, " | " + СтрСоединить(Предупреждения, "; "), "")
		+ " ## " + СтрСоединить(Части, " ## ");
	ЗафиксироватьТранзакцию();
Исключение
	ОтменитьТранзакцию();
	ВызватьИсключение ОписаниеОшибки();
КонецПопытки;

Результат = Итог;
'''


def build_payload(positions, mark_delete=False, order_comment=""):
    b64 = base64.b64encode(
        json.dumps(positions, ensure_ascii=False).encode()
    ).decode()
    if not order_comment:
        order_comment = "Загрузка из JSON (execute_code, build_execute_payload)"
    # кавычки 1С в строковом литерале удваиваются
    order_comment = order_comment.replace('"', '""')
    code = BSL_TEMPLATE.format(
        b64=b64,
        mark_delete="" if mark_delete else "// ",
        order_comment=order_comment,
    )
    return {"code": code}


if __name__ == "__main__":
    if len(sys.argv) < 2:
        print(__doc__, file=sys.stderr)
        sys.exit(1)
    positions = json.load(open(sys.argv[1], encoding="utf-8"))
    mark_delete = "--mark-delete" in sys.argv
    json.dump(build_payload(positions, mark_delete), sys.stdout, ensure_ascii=False)
